print("\n--- Q113: Menu-Driven Calculator ---")

a = 15
b = 4

print("First Number:", a)
print("Second Number:", b)

# Addition
add = a + b
print("Addition =", add)

# Subtraction
subtract = a - b
print("Subtraction =", subtract)

# Multiplication
multiply = a * b
print("Multiplication =", multiply)

# Division
divide = a / b
print("Division =", divide)

# Modulus
modulus = a % b
print("Modulus =", modulus)

# Power
power = a ** b
print("Power =", power)